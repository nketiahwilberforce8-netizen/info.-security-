/**
 * ============================================================================
 * NKETIAH SCHOOL MANAGEMENT SYSTEM - FIRESTORE DATABASE SCHEMA & TYPES
 * ============================================================================
 *
 * TEACHING NOTE ON FIRESTORE CONCEPTS:
 * 1. Collection: A container for documents (similar to a table in SQL).
 *    Our 6 collections:
 *    - `users`         : Stores user credentials, Argon2id hashes, encrypted TOTP secrets, roles, and lockout state.
 *    - `sessions`      : Stores SHA-256 hashed refresh tokens for session revocation and rotation.
 *    - `recoveryCodes` : Stores one-time 2FA backup recovery code hashes for each user.
 *    - `schoolNotices` : Stores NKETIAH School academic announcements, courses, and portal notices.
 *    - `auditLogs`     : Immutable security event trail (logins, 2FA events, role changes, backups).
 *    - `backupLogs`    : Tracks automated and manual database backups and restoration events.
 *
 * 2. Document: A JSON-like record stored inside a collection.
 * 3. Document ID: A unique string identifier (e.g., `usr_9f8a7b6c...`) generated by the backend.
 *    Users NEVER log in with their Document ID; they log in ONLY with `username` + `password` (+ `2FA`).
 */

export type UserRole = 'GUEST' | 'USER' | 'ADMIN';

export type AccountStatus = 'ACTIVE' | 'DISABLED';

/**
 * Encrypted Payload Format for AES-256-GCM
 * Stored in Firestore whenever sensitive data (like a TOTP Secret) must be decrypted later.
 */
export interface AesGcmEncryptedPayload {
  algorithm: 'aes-256-gcm';
  ivHex: string;         // 12-byte (96-bit) unique Initialization Vector / Nonce
  authTagHex: string;    // 16-byte (128-bit) Galois Message Authentication Code Tag
  ciphertextHex: string; // Encrypted data bytes in hexadecimal
  keyVersion: number;    // Supports key rotation awareness
}

/**
 * Collection: `users`
 * Document ID: Internal UUID (`id`)
 */
export interface UserDocument {
  id: string;                                      // Internal document ID (never required for login)
  username: string;                                // Display username (e.g., "Kwame_Nketiah")
  usernameNormalized: string;                      // Lowercase indexed username for uniqueness ("kwame_nketiah")
  fullName: string;                                // Student / Staff / Admin Full Name
  department: string;                              // e.g., "Information Technology", "Administration", "Computer Science"
  studentOrStaffId: string;                        // e.g., "NK-STU-2026-001" or "NK-ADM-001"
  role: UserRole;                                  // 'USER' | 'ADMIN' (Unauthenticated visitors are 'GUEST')
  status: AccountStatus;                           // 'ACTIVE' | 'DISABLED'
  passwordHash: string;                            // Argon2id encoded hash (includes algorithm params + unique 16-byte salt)
  twoFactorEnabled: boolean;                       // Whether TOTP 2FA is active
  totpSecretEncrypted: AesGcmEncryptedPayload | null; // Confirmed TOTP secret encrypted with AES-256-GCM
  pendingTotpSecretEncrypted: AesGcmEncryptedPayload | null; // Temporary TOTP secret during QR setup before verification
  failedLoginAttempts: number;                     // Brute-force counter
  lockoutUntil: string | null;                     // ISO timestamp if account is temporarily locked
  lastLoginAt: string | null;                      // ISO timestamp of last successful authentication
  createdAt: string;                               // ISO timestamp
  updatedAt: string;                               // ISO timestamp
}

/**
 * Safe User DTO (Data Transfer Object) returned to React Web & Expo Mobile clients.
 * NEVER includes passwordHash, totpSecretEncrypted, or pendingTotpSecretEncrypted!
 */
export interface SafeUserDTO {
  id: string;
  username: string;
  fullName: string;
  department: string;
  studentOrStaffId: string;
  role: UserRole;
  status: AccountStatus;
  twoFactorEnabled: boolean;
  lastLoginAt: string | null;
  createdAt: string;
  updatedAt: string;
}

/**
 * Collection: `sessions`
 * Stores hashed refresh tokens so sessions can be rotated and revoked immediately.
 */
export interface SessionDocument {
  id: string;
  userId: string;
  username: string;
  refreshTokenHash: string; // SHA-256 hash of the refresh token
  userAgent: string;
  ipAddress: string;
  revoked: boolean;
  expiresAt: string;        // ISO timestamp
  createdAt: string;        // ISO timestamp
  rotatedAt: string | null; // ISO timestamp
}

/**
 * Collection: `recoveryCodes`
 * Stores hashed one-time recovery codes for 2FA emergency access.
 */
export interface RecoveryCodeEntry {
  codeHash: string;         // SHA-256 + Pepper hash of the recovery code
  used: boolean;
  usedAt: string | null;
}

export interface RecoveryCodesDocument {
  id: string;               // Matches userId
  userId: string;
  codes: RecoveryCodeEntry[];
  generatedAt: string;
}

/**
 * Collection: `schoolNotices`
 * NKETIAH School Management System academic announcements, courses & bulletins.
 */
export interface SchoolNoticeDocument {
  id: string;
  title: string;
  category: 'ACADEMIC' | 'SECURITY' | 'ADMISSIONS' | 'EXAMINATIONS' | 'GENERAL';
  content: string;
  visibility: 'PUBLIC' | 'AUTHENTICATED_ONLY' | 'ADMIN_ONLY';
  authorUsername: string;
  authorRole: UserRole;
  createdAt: string;
  updatedAt: string;
}

/**
 * Collection: `auditLogs`
 * Security audit trail. Never stores plaintext passwords, TOTP secrets, or keys.
 */
export type AuditEventType =
  | 'REGISTER_SUCCESS'
  | 'LOGIN_SUCCESS'
  | 'LOGIN_FAILED'
  | 'ACCOUNT_LOCKED'
  | '2FA_SETUP_INITIATED'
  | '2FA_ENABLED'
  | '2FA_DISABLED'
  | '2FA_VERIFY_SUCCESS'
  | '2FA_VERIFY_FAILED'
  | '2FA_RECOVERY_CODE_USED'
  | 'PASSWORD_CHANGED'
  | 'TOKEN_REFRESHED'
  | 'LOGOUT'
  | 'ADMIN_ROLE_CHANGED'
  | 'ADMIN_STATUS_CHANGED'
  | 'ADMIN_USER_DELETED'
  | 'SCHOOL_NOTICE_CREATED'
  | 'SCHOOL_NOTICE_DELETED'
  | 'BACKUP_CREATED'
  | 'BACKUP_FAILED'
  | 'DATABASE_RESTORED'
  | 'UNAUTHORIZED_ACCESS_ATTEMPT';

export interface AuditLogDocument {
  id: string;
  eventType: AuditEventType;
  severity: 'INFO' | 'WARNING' | 'CRITICAL';
  actorUserId: string | null;
  actorUsername: string | null;
  targetUserId: string | null;
  targetUsername: string | null;
  ipAddress: string;
  userAgent: string;
  details: string;
  metadata?: Record<string, string | number | boolean | null>;
  createdAt: string;
}

/**
 * Collection: `backupLogs`
 * Tracks every automated and manual database backup & restoration.
 */
export interface BackupLogDocument {
  id: string;
  backupId: string;
  filename: string;
  triggerType: 'AUTOMATED_CRON' | 'MANUAL_CLI' | 'ADMIN_API';
  status: 'SUCCESS' | 'FAILED' | 'RESTORED';
  storageLocation: 'FIREBASE_CLOUD_STORAGE_AND_LOCAL' | 'LOCAL_ENCRYPTED_VAULT';
  cloudBucketPath: string | null;
  localFilePath: string;
  sizeBytes: number;
  checksumSha256: string;
  encryptionAlgorithm: 'aes-256-gcm';
  collectionCounts: {
    users: number;
    sessions: number;
    recoveryCodes: number;
    schoolNotices: number;
    auditLogs: number;
  };
  triggeredByUsername: string;
  errorMessage: string | null;
  createdAt: string;
  restoredAt: string | null;
}
